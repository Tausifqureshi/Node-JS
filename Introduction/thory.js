// --------------------------------------------- Node.js ka Introduction --------------------------------------------- //
// ChatGPT Se Liya Hua Syntex ---> Node.js Kya Hai.
// Node.js ek open-source, cross-platform JavaScript runtime environment hai jo Chrome ke V8 engine par built hai. Ye server-side aur networking applications banane ke liye use hota hai.

// --------------------------------------------- Node.js ki Key Features --------------------------------------------- //
// ChatGPT Se Liya Hua Syntex ---> Node.js ki Key Features.
// 1. Asynchronous and Event-Driven: Node.js ki sabhi APIs asynchronous (non-blocking) hoti hain. Server data ka wait nahi karta balke next API par move kar jata hai.
// 2. Fast Execution: Chrome ke V8 engine par based hone ki wajah se, Node.js code execution me bahut fast hai.
// 3. Single-Threaded but Highly Scalable: Ye single thread model event looping ke sath use karta hai jo ise highly scalable banata hai compared to traditional servers.
// 4. No Buffering: Node.js applications data ko buffer nahi karti hain, ye simply data ko chunks me output karti hain.
// 5. NPM (Node Package Manager): Duniya ka sabse bada software registry jisme hazaro free libraries/packages available hain jo development ko fast banate hain.

// --------------------------------------------- Node.js ka History --------------------------------------------- //
// ChatGPT Se Liya Hua Syntex ---> Node.js ki History.
// 1. 2009: Ryan Dahl ne Node.js ko create kiya. Us time pe ye sirf Linux aur Mac OS par chalta tha. Isne browser ke bahar JavaScript ko run karna possible banaya.
// 2. 2010: NPM (Node Package Manager) introduce hua, jisse developers ke liye third-party modules/packages share aur reuse karna aasan ho gaya.
// 3. 2011: Microsoft aur Joyent ne milkar Node.js ka native Windows version release kiya, jisse ye Windows users ke liye bhi available ho gaya.
// 4. 2014-2015: Kuch developers ne milkar io.js naam se ek fork banaya taaki ES6 features jaldi mil sake. 2015 me Node.js Foundation bani aur io.js ko Node.js me wapas merge kar diya gaya.

// --------------------------------------------- Node.js Major Updates --------------------------------------------- //
// ChatGPT Se Liya Hua Syntex ---> Node.js Ke Major Updates.
// 1. Node.js 4 (September 2015)
// Update: io.js merge hone ke baad ye pehla major release tha jisme ES6 (ECMAScript 2015) features ka support laya gaya.
// Key Benefit: Developers ke liye modern JavaScript features use karna aur LTS (Long Term Support) plan introduce hua.

// 2. Node.js 8 (May 2017)
// Update: V8 engine upgrade hua aur N-API introduce hui (jo native addons bananane me help karti hai).
// Key Benefit: Performance me massive improvement aya aur native modules jyada stable ho gaye.

// 3. Node.js 10 (April 2018)
// Update: npm v6 ke sath aya, aur experimental fs.promises API add hui.
// Key Benefit: Security features better hue aur file system me promise-based operations (async/await) use karna asan hua.

// 4. Node.js 14 (April 2020)
// Update: Optional Chaining, Nullish Coalescing aur Async Local Storage introduce hue.
// Key Benefit: Complex data structures ko handle karna aur code likhna jyada clean aur asan ho gaya.

// 5. Node.js 18 (April 2022)
// Update: Native Fetch API, Web Streams API aur Test Runner module built-in aaye.
// Key Benefit: Third-party packages (jaise axios ya node-fetch) ki basic HTTP requests ke liye zarurat kam ho gayi aur standard web APIs directly Node me milne lagi.

// 6. Node.js 20 (April 2023)
// Update: Permission Model (experimental) aur stable Test Runner laya gaya, aur V8 engine ka latest version add hua.
// Key Benefit: Security bahut strong ho gayi (file system aur network access restrict kar sakte hain) aur built-in testing reliable ho gayi.
