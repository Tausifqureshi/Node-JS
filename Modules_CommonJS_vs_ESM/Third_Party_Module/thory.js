// ========================================= Third-Party Modules Kya Hain? ======================================= //
// Node.js me kuch modules na to Core modules hote hain (jo pehle se aate hain) aur na hi Local modules (jo hum khud banate hain).
// Ye modules poori duniya ke doosre developers ne banakar internet par daale hote hain, taaki humara kaam aasan ho jaye.
// In modules ko hum "NPM" (Node Package Manager) ka use karke internet se download karte hain.
// Isliye inhein "Third-Party Modules" kaha jata hai (kyunki ye humne ya Node.js walo ne nahi banaye, kisi teesre insaan ne banaye hain).

// 📌 Main Kaam: Doosre developers ka bana banaya code apne project me use karke apna time aur mehnat bachana.

/*
NPM se Download Kaise Karein?
1. Terminal open karein aur command likhein: 'npm init -y' (Ye ek package.json file bana dega).
2. Fir jo module chahiye wo download karein, jaise Express (Server banane ke liye): 'npm install express'

Third-Party Modules ke Examples:
1. 'express' -> Sabse popular web framework (API aur Server banane ke liye).
2. 'mongoose' -> MongoDB database ke sath connect aur kaam karne ke liye.
3. 'nodemon' -> Jab bhi hum code change karein, toh server ko baar-baar manually restart nahi karna padta, nodemon automatically kar deta hai.
4. 'dotenv' -> Secret keys (jaise passwords) ko secure rakhne ke liye.

Bade Projects Me Kab Kaam Aata Hai?
- Asal zindagi me, bina third-party modules ke Node.js ka koi bhi bada project banta hi nahi hai. Express, Mongoose jaisi cheezein har project me chahiye hi hoti hain.
*/
